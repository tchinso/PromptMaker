"""Record atlas dimensions and visually audited separator insets (no image edits)."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "site" / "assets" / "visual-guides" / "options"
# These sheets contain wider outer gutters or rounded gold frames.
FRAMED = {
    "thumb-outfit-uniform-details-v2.png", "thumb-props-hand-v2.png",
    "thumb-props-jewelry-v2.png", "thumb-props-decor-v2.png",
    "thumb-props-hair-accessory-v2.png",
}
WIDE_GUTTER = {
    "thumb-eye-pupil-v2.png", "thumb-outfit-tech-v2.png",
    "thumb-outfit-materials-v1.png", "thumb-outfit-trad-goth-fantasy-v1.png",
    "thumb-scene-romance-tone-v2.png", "thumb-props-accessories-v1.png",
}
metadata = {}
bounds_path = ROOT / "tools" / "atlas_cell_bounds.json"
measured = json.loads(bounds_path.read_text(encoding="utf-8")) if bounds_path.exists() else {}
for path in sorted(DIRECTORY.glob("*.png")):
    with Image.open(path) as image:
        width, height = image.size
    metadata[path.name] = {
        "width": width, "height": height,
        "inset": 0.09 if path.name == "thumb-props-accessories-v1.png" else 0.08 if path.name in FRAMED else 0.055 if path.name in WIDE_GUTTER else 0.04,
    }
    if path.name in measured:
        spec = measured[path.name]
        if isinstance(spec, dict) and spec.get("sourceSize"):
            assert spec["sourceSize"] == {"width": width, "height": height}, f"Re-measure changed artwork: {path.name}"
        cells = spec if isinstance(spec, list) else spec["cells"]
        assert len(cells) == 12, f"Expected 12 logical cells: {path.name}"
        for cell in cells:
            assert cell["x"] >= 0 and cell["y"] >= 0 and cell["width"] > 0 and cell["height"] > 0
            assert cell["x"] + cell["width"] <= width and cell["y"] + cell["height"] <= height
            assert 0 <= cell.get("anchorX", .5) <= 1 and 0 <= cell.get("anchorY", .5) <= 1
        metadata[path.name]["cells"] = cells
assert FRAMED | WIDE_GUTTER <= metadata.keys()
(ROOT / "site" / "atlas-crops.js").write_text(
    "// Generated by tools/build_atlas_crops.py; measurements do not modify source artwork.\n"
    + "window.PM_ATLAS_CROPS = " + json.dumps(metadata, ensure_ascii=False, indent=2) + ";\n",
    encoding="utf-8",
)
print(f"Recorded {len(metadata)} atlas sizes and audited crop insets.")
